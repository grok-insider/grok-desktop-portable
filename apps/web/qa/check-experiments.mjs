 await page.getByText('This folder changed on the computer. Select it again before adding it.').waitFor();
 check('stale folder refusal visible',true);
 await page.evaluate(()=>remoteQa.folderRefused(false));
 await page.getByRole('button',{name:'Use this folder as a project'}).click();
 await page.waitForTimeout(100);
 check('enroll uses opaque handle',await page.evaluate(()=>remoteQa.commands.filter(c=>c.operation?.kind==='enrollRemoteProject').every(c=>c.operation.directoryId==='opaque-root' && !('path' in c.operation))));
 await page.getByRole('button',{name:'Browse approved folders'}).click();
 await page.getByRole('button',{name:'Browsers and control'}).click();
