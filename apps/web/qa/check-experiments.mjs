 await page.reload();
 await input.waitFor();
 await page.locator('[data-draft-status="saved"]').waitFor();
 check('opted draft restored',await input.inputValue()==='Preserved draft');
 await page.evaluate(()=>remoteQa.share('Shared synthetic text'));
 const append=page.getByRole('button',{name:/Add to .* draft/});
 await append.waitFor();
