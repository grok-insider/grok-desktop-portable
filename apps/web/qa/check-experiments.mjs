 check('draft unchanged before consent',await input.inputValue()==='Preserved draft');
 await append.click();
 await page.waitForTimeout(200);
 check('explicit share appends to preserved draft',await input.inputValue()==='Preserved draft\n\nShared synthetic text');
 check('share cleaned up',await page.evaluate(async()=> (await remoteQa.shareInbox.readShareInbox()).length===0));
 await page.getByRole('button',{name:'Browse approved folders'}).click();
 await page.getByRole('button',{name:'Browse QA approved root'}).click();
