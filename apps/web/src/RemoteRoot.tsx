const APPLE_OPT_IN = "grok-apple-experimental-v1";

export function isAppleDevice(userAgent = navigator.userAgent, platform = navigator.platform, touchPoints = navigator.maxTouchPoints): boolean {
  return /Macintosh|Mac OS X|iPhone|iPad|iPod/i.test(userAgent) || /Mac/i.test(platform) || platform === "MacIntel" && touchPoints > 1;
}

function appleOptIn(): boolean {
  if (!isAppleDevice()) return true;
  try {return localStorage.getItem(APPLE_OPT_IN) === "yes";} catch {return false;}
}

const ERRORS: Record<string, string> = {
  pairing_required: "Open the pairing link generated by Spanreed on your computer.",
  pairing_rejected: "The pairing code expired or was already used. Generate a new code on your computer.",
  revoked: "This browser’s access was revoked. Generate a new pairing link on your computer.",
  protocol_mismatch: "This computer and app use different protocol versions. Update Spanreed and the app. Your pairing and drafts are preserved.",
  protocol_error: "The computer returned an invalid response. Check Spanreed and reconnect. Your pairing and drafts are preserved.",
  host_identity_changed: "The computer’s installation changed. Generate a new pairing link on the computer.",
  host_key_changed: "The computer’s identity key changed. Generate a new pairing link on the computer.",
  pairing_changed: "This computer’s pairing changed in another tab. Return to Computers and connect again.",
  crypto_unavailable: "The app’s encryption module is unavailable. Install a complete app update before connecting.",
  device_storage_unavailable: "This browser cannot save the pairing. Enable site storage, then try again.",
  device_storage_invalid: "Saved computer data could not be read. Keep a copy of your drafts before clearing site data.",
  computer_limit: "This browser already has 32 computers. Forget an unused computer before adding another.",
};

export function RemoteRoot({publicationCallback: initialCallback = null}: {publicationCallback?: PublicationCallback} = {}) {
  const [publicationCallback, setPublicationCallback] = useState(initialCallback);
  const [profiles, setProfiles] = useState<DirectProfile[]>([]);
  const [pairing, setPairing] = useState(takeDirectPairing);
  const [selected, setSelected] = useState<{profile: DirectProfile; client: LightClient} | null>(null);
  const [busy, setBusy] = useState(false);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string>();
  const [enabled, setEnabled] = useState(appleOptIn);
  const lifecycle = useRef(0);
  const current = useRef<typeof selected>(null);
  const abort = useRef<AbortController | null>(null);
  const refresh = useCallback(async () => {
    const generation = lifecycle.current;
    try {
      const values = await listDirectProfiles();
      if (generation !== lifecycle.current) return;
      setProfiles(values);
      const active = current.current;
      if (active) {
        const latest = values.find(profile => directProfileId(profile) === directProfileId(active.profile));
        if (!latest || latest.pair.sessionId !== active.profile.pair.sessionId || latest.hostPublicKey !== active.profile.hostPublicKey) {
          lifecycle.current++;
          active.client.dispose();
          current.current = null;
          setSelected(null);
          setError(ERRORS.pairing_changed);
        }
      }
    } catch (failure) {
      if (generation === lifecycle.current) setError(ERRORS[failure instanceof Error ? failure.message : "device_storage_unavailable"] ?? ERRORS.device_storage_unavailable);
    } finally {if (generation === lifecycle.current) setLoading(false);}
  }, []);

  useEffect(() => {
    lifecycle.current++;
    void refresh();
    const stopObserving = observeDirectProfiles(() => {void refresh();});
    const incoming = () => {
      const next = takeDirectPairing();
      if (!next) return;
      lifecycle.current++;
      abort.current?.abort();
      current.current?.client.dispose();
      current.current = null;
      setSelected(null);
      setBusy(false);
      setPairing(next);
      setError(undefined);
      void refresh();
    };
    window.addEventListener("hashchange", incoming);
    return () => {
      lifecycle.current++;
      abort.current?.abort();
      current.current?.client.dispose();
      stopObserving();
      window.removeEventListener("hashchange", incoming);
    };
  }, [refresh]);

  const connect = async (profile?: DirectProfile) => {
    const pendingPair = profile ? undefined : pairing ?? undefined;
    if (!enabled || (!profile && !pendingPair)) return;
    const generation = ++lifecycle.current;
    abort.current?.abort();
    const controller = new AbortController();
    abort.current = controller;
    setBusy(true);
    setError(undefined);
    try {
      const result = await createDirectTransport({profile, pairing: pendingPair, signal: controller.signal});
      if (generation !== lifecycle.current) {result.transport.dispose?.(); return;}
      const client = new LightClient({transport: result.transport, storageKey: `grok-direct-session.v1:${directDraftScope(result.profile)}`});
      const next = {client, profile: result.profile};
      current.current = next;
      setSelected(next);
      if (pendingPair) setPairing(null);
      void refresh();
    } catch (failure) {
      if (generation !== lifecycle.current) return;
      if (profile && failure instanceof Error && failure.message === "revoked") {
        try {await forgetDraftScope(directDraftScope(profile));}
        catch {if (generation === lifecycle.current) setError("Access was revoked, but saved browser data could not be deleted. Clear this browser’s site data before sharing the device."); return;}
        if (generation !== lifecycle.current) return;
      }
      setError(ERRORS[failure instanceof Error ? failure.message : ""] ?? "The computer could not be reached. Check its connection, Tailscale or HTTPS address, and that Spanreed is running. Then reconnect.");
      void refresh();
    } finally {if (generation === lifecycle.current) setBusy(false);}
  };

  const forgetSelected = async () => {
    const active = current.current;
    if (!active) return;
    const generation = lifecycle.current;
    setBusy(true);
    setError(undefined);
    let confirmed = false;
    try {
      const result = await active.client.revokePairing();
      if (generation !== lifecycle.current) return;
      if (!result.ok && result.failure.kind !== "not_paired") throw new Error("revocation_unconfirmed");
      confirmed = true;
      await forgetDraftScope(directDraftScope(active.profile));
      if ("serviceWorker" in navigator) await removeDirectPushRegistration(directDraftScope(active.profile));
      if (generation !== lifecycle.current) return;
      current.current = null;
      await active.client.forgetPairing();
      if (generation !== lifecycle.current) return;
      setSelected(null);
      await refresh();
    } catch (failure) {
      if (generation === lifecycle.current) setError(confirmed ? "Access was revoked, but saved browser data could not be deleted. Clear this browser’s site data before sharing the device." : "The computer did not confirm revocation. Reconnect and try again, or revoke this browser from Spanreed on the computer.");
      throw failure;
    } finally {if (generation === lifecycle.current) setBusy(false);}
  };

  if (selected) return <div className="remote-connected">
    <div className="remote-host-bar flex min-h-12 items-center gap-2 border-b border-border bg-background px-2"><Button variant="ghost" size="sm" aria-label="Computers" disabled={busy} onClick={() => {lifecycle.current++; abort.current?.abort(); selected.client.dispose(); current.current = null; setSelected(null); void refresh();}}><ArrowLeft size={18} aria-hidden="true" /><span className="max-[680px]:sr-only">Computers</span></Button><span className="min-w-0 flex-1 truncate font-semibold" title={selected.profile.label}>{selected.profile.label}</span><Button variant="ghost" size="sm" aria-label="Forget this browser" disabled={busy} onClick={() => {void forgetSelected().catch(() => {});}}><Unplug size={18} aria-hidden="true" /><span className="max-[680px]:sr-only">Forget this browser</span></Button></div>
    {error && <Alert variant="warning" className="rounded-none border-x-0"><AlertDescription>{error}</AlertDescription></Alert>}
    {publicationCallback && <PublicationAuthorization key={directDraftScope(selected.profile)} client={selected.client} profileId={directDraftScope(selected.profile)} callback={publicationCallback} onComplete={() => setPublicationCallback(null)} />}
    <App key={directDraftScope(selected.profile)} client={selected.client} draftScope={directDraftScope(selected.profile)} onRevokeOwn={forgetSelected} />
  </div>;

  return <main className="remote-home">
    <PageHeader title="Your computers" description="Continue your Grok terminal sessions over a private connection to Spanreed." actions={<ThemeToggle />} />
    {error && <Alert variant="warning"><AlertDescription>{error}</AlertDescription></Alert>}
    {publicationCallback && <Alert><AlertDescription>{"error" in publicationCallback ? publicationCallback.error : "Connect the computer used to authorize publications to finish."}</AlertDescription></Alert>}
    {!enabled ? <Card><h2 className="font-semibold">Apple support is experimental</h2><p className="mt-2 text-muted-foreground">macOS, iPhone and iPad have not been qualified on real devices. Installation, keyboard, background connections and notifications may be unreliable.</p><Button className="mt-3" onClick={() => {try {localStorage.setItem(APPLE_OPT_IN, "yes");} catch {}setEnabled(true);}}>Enable experimental Apple support</Button></Card> : <>
      <ShareInbox />
      {pairing && <Card><h2 className="font-semibold">Pair {pairing.label ?? "this computer"}</h2><p className="mt-1 break-all font-mono text-body-sm text-muted-foreground">{pairing.endpoint}</p><p className="mt-3 text-body-sm text-muted-foreground">Only continue if you generated this link in Spanreed on that computer.</p><div className="mt-4 flex flex-wrap gap-2"><Button variant="primary" disabled={busy} onClick={() => {void connect();}}>Pair and connect</Button><Button disabled={busy} onClick={() => setPairing(null)}>Discard link</Button></div></Card>}
      {loading && <p role="status" className="text-muted-foreground">Reading saved computers…</p>}
      {profiles.length > 0 && <ItemGroup bordered>{profiles.map(profile => <Item key={directProfileId(profile)}><ItemMedia variant="icon"><Monitor aria-hidden="true" /></ItemMedia><ItemContent><ItemTitle render={<h2 />} className="break-words">{profile.label}</ItemTitle><ItemDescription className="break-all font-mono">{profile.endpoint}</ItemDescription></ItemContent><ItemActions className="flex-wrap"><OfflineHistory scope={directDraftScope(profile)} /><Button variant="primary" disabled={busy} onClick={() => {void connect(profile);}}>Connect</Button></ItemActions></Item>)}</ItemGroup>}
      {!loading && !profiles.length && !pairing && <Card><h2 className="font-semibold">Add your first computer</h2><p className="mt-2 text-muted-foreground">On your computer, configure Spanreed with Tailscale or your own HTTPS domain. Keep the computer on and Spanreed running.</p><p className="mt-2 text-muted-foreground">Run <code className="font-mono text-body-sm">spanreed remote private-pair https://your-computer</code> and open the generated QR link on this device.</p></Card>}
      <TerminalSessionHelp className="text-body-sm text-muted-foreground" />
      <p className="text-body-sm text-muted-foreground">Your computer list and pairing stay in this browser. Private conversations, files and commands connect directly to your computer. The installed app can open without our website when your computer is reachable.</p>
    </>}
    <footer className="flex justify-start"><SourceLicense /></footer>
  </main>;
}
